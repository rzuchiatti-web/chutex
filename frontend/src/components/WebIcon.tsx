interface IconProps {
  name: string;
  size?: number;
  color?: string;
  style?: any;
}

export function Icon({ name, size = 20, color = '#1A1D21', style }: IconProps) {
  if (Platform.OS !== 'web') {
    const { Ionicons } = require('@expo/vector-icons');
    return <Ionicons name={name} size={size} color={color} style={style} />;
  }

  const icon = SVG_ICONS[name];
  if (!icon) {
    return <View style={[{ width: size, height: size }, style]} />;
  }

  return (
    <View style={[{ width: size, height: size }, style]}>
      <svg width={size} height={size} viewBox="0 0 24 24" fill="none" xmlns="http://www.w3.org/2000/svg">
        <path d={icon.path} stroke={color} strokeWidth="1.8" strokeLinecap="round" strokeLinejoin="round" />
      </svg>
    </View>
  );
}

export function MCIcon({ name, size = 20, color = '#1A1D21', style }: IconProps) {
  if (Platform.OS !== 'web') {
    const { MaterialCommunityIcons } = require('@expo/vector-icons');
    return <MaterialCommunityIcons name={name} size={size} color={color} style={style} />;
  }
  return <Icon name={name} size={size} color={color} style={style} />;
}
